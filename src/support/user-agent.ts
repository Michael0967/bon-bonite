let lastIndex = -1;

export function getRandomUserAgent(): string {
  let index: number;
  do {
    index = Math.floor(Math.random() * DESKTOP_USER_AGENTS.length);
  } while (index === lastIndex && DESKTOP_USER_AGENTS.length > 1);
  lastIndex = index;
  return DESKTOP_USER_AGENTS[index];
}
